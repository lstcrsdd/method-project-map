"""Candidate copies of one piece of logic written by hand in several languages, found by the string literals they
use, never by their names alone.

A team that ports one piece of logic to every client (a stream-link parser in Swift, C#, Java and Rust) keeps
copies no compiler compares. Each copy uses the same keys: the same string literals, directly or through string
constants (`tag::REMOTE` in Rust, `Tag.remote` in Swift). `find_twins` pairs functions of different languages by
the overlap of those vocabularies, weighted by how rare each literal is in the project, keeps pairs that choose
each other, and groups them. A group is a candidate, not a proof: it may be a hand-written copy, the other end of
one format (one side writes the keys, the other reads them: listed apart), or two functions that happen to share
an enum's strings. Nothing here says which copy is right. `pmap twins --exec` (pmap/twins_exec.py) runs the
copies on the same inputs and compares their outputs.

Static, deterministic, no LLM: the source is read with regular expressions over the files the map covers.
"""

