@dataclass
class TwinMember:
    node_id: str
    language: str
    path: str
    line_start: int
    line_end: int
    name: str
    vocabulary_size: int
    shared_count: int  # keys of this copy that a copy in another language of the group uses too
    reach: str
    same_language: bool = False  # joined through a cross-language pair only: another copy in a language present
    score: float = 0.0  # its best pair in the group (literal overlap, capped at 1)
    partner: str = ""  # the name of that pair's other function
    pair_shared: int = 0  # literals that pair shares
    same_name: bool = False

    def to_dict(self) -> Dict[str, Any]:
        return {"node_id": self.node_id, "language": self.language, "path": self.path, "line_start": self.line_start,
                "line_end": self.line_end, "name": self.name, "vocabulary_size": self.vocabulary_size,
                "shared_count": self.shared_count, "reach": self.reach, "same_language": self.same_language,
                "score": self.score, "partner": self.partner, "pair_shared": self.pair_shared,
                "same_name": self.same_name}

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "TwinMember":
        return cls(**{k: data[k] for k in ("node_id", "language", "path", "line_start", "line_end", "name",
                                          "vocabulary_size", "shared_count", "reach")},
                   same_language=bool(data.get("same_language", False)), score=float(data.get("score", 0.0)),
                   partner=str(data.get("partner", "")), pair_shared=int(data.get("pair_shared", 0)),
                   same_name=bool(data.get("same_name", False)))


@dataclass
class TwinGroup:
    id: str
    title: str
    score: float  # mean literal overlap of the pairs that formed the group, capped at 1: not a probability
    members: List[TwinMember] = field(default_factory=list)
    evidence: List[str] = field(default_factory=list)  # the rarest literals the languages share
    kind: str = "copies"  # or "ends": one side writes the keys, the other reads them (two ends of one format)
    more_evidence: int = 0  # shared literals left out of `evidence`
    links: List[List[Any]] = field(default_factory=list)  # [id, id, overlap, shared] for every cross-language pair

    def to_dict(self) -> Dict[str, Any]:
        return {"id": self.id, "title": self.title, "score": self.score, "kind": self.kind,
                "members": [m.to_dict() for m in self.members], "evidence": list(self.evidence),
                "more_evidence": self.more_evidence, "links": [list(x) for x in self.links]}

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "TwinGroup":
        return cls(id=data["id"], title=data["title"], score=float(data["score"]),
                   members=[TwinMember.from_dict(m) for m in data.get("members", [])],
                   evidence=list(data.get("evidence", [])), kind=str(data.get("kind", "copies")),
                   more_evidence=int(data.get("more_evidence", 0)), links=[list(x) for x in data.get("links", [])])


# ====================================================================== reading the source


def language_of(path: str) -> str:
    from pmap.langs import EXT_TO_LANGUAGE

    return "python" if path.endswith(".py") else EXT_TO_LANGUAGE.get(posixpath.splitext(path)[1], "")


def family_of(language: str) -> str:
    return FAMILIES.get(language, language)


def is_test_path(path: str) -> bool:
    return bool(TEST_PATH.search(path))


def is_example_path(path: str) -> bool:
    return bool(EXAMPLE_PATH.search(path))


def is_side_path(path: str) -> bool:
    """Examples, tests and fixtures: when two candidates tie, the library function is the copy, not its demo."""
    return is_test_path(path) or is_example_path(path)


class _Source:
    """One file with its comments blanked and its string literals set aside (offsets kept, so lines match)."""

    def __init__(self, path: str, text: str, language: str) -> None:
        text = text.replace("\r\n", "\n")  # a CRLF checkout: `= "x"\r` must still end a declaration
        self.path, self.text, self.language = path, text, language
        self.strings: Dict[int, Tuple[int, str]] = {}  # token start -> (end, value)
        lexer = _LEXERS["python" if language == "python" else "quote" if language in _QUOTE_LANGS else "c"]
        parts: List[str] = []
        last = 0
        for m in lexer.finditer(text):
            tok = m.group(0)
            parts.append(text[last:m.start()])
            if tok.startswith("#" if language == "python" else ("//", "/*")):
                parts.append(_blank(tok))
            else:  # a string keeps a quote at both ends: the declaration patterns look for where it starts
                value = _string_value(tok)
                if value is not None:
                    self.strings[m.start()] = (m.end(), value)
                parts.append('"' + _blank(tok[1:-1]) + '"')
            last = m.end()
        parts.append(text[last:])
        self.code = "".join(parts)
        self.string_offsets = sorted(self.strings)
        self.line_starts = [0] + [m.end() for m in re.finditer(r"\n", text)]

    def line_of(self, offset: int) -> int:
        return bisect.bisect_right(self.line_starts, offset)

    def offset_of(self, line: int) -> int:
        return self.line_starts[min(max(line, 1), len(self.line_starts)) - 1]

    def strings_between(self, start: int, end: int) -> Iterable[Tuple[int, str]]:
        offsets = self.string_offsets
        for offset in offsets[bisect.bisect_left(offsets, start):bisect.bisect_left(offsets, end)]:
            yield offset, self.strings[offset][1]


def _blank(text: str) -> str:
    return " " * len(text) if "\n" not in text else re.sub(r"[^\n]", " ", text)


def _string_value(tok: str) -> Optional[str]:
    """The text of a literal without its quotes and prefix; None for one that interpolates or escapes."""
    m = re.match(r"([A-Za-z@0-9]*)(#*)(\"\"\"|'''|[\"'`])", tok)
    if m is None:
        return None
    quote = m.group(3)
    body = tok[m.end():len(tok) - len(quote) - len(m.group(2))] if tok.endswith(quote + m.group(2)) else None
    if body is None or "\\" in body or "${" in body or (m.group(1).lower().startswith("f") and "{" in body):
        return None
    return body


def _read(root: Path, rel: str) -> Optional[str]:
    """The file's text; None when it cannot be read or says it is generated."""
    try:
        data = (root / rel).read_bytes()
    except OSError:
        return None
    if GENERATED_MARK.search(data[:600]):
        return None
    return data.decode("utf-8", errors="replace")


def _role(code: str, start: int, end: int) -> str:
    """'w' when the literal (or constant) at code[start:end] is written as a key, 'r' when it is read, else ''."""
    before = code[max(0, start - 60):start].rstrip()
    after = code[end:end + 16]
    if re.search(r"(?:\bcase|==|!=)\s*$", before) or re.match(r"\s*(?:==|!=|=>|\|)", after):
        return "r"  # compared or matched: `case "k":`, Rust and C# match arms `"k" | "x" => ...`
    if before.endswith("["):
        if re.match(r"\s*\]\s*=(?!=)", after):
            return "w"
        if re.match(r"\s*\]", after):
            return "r"
    if re.match(r"\s*(?::(?!:)|to\b)", after):
        return "w"
    if _WRITE_CALL.search(before):
        return "w"
    if _READ_CALL.search(before):
        return "r"
    return ""


