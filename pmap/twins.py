@dataclass
class _Scope:
    start: int
    end: int
    name: Optional[str]
    test: bool = False


def _scopes(src: _Source) -> List[_Scope]:
    """Named containers (types, modules, impl blocks) by offset; `#[cfg(test)] mod` is marked as test code."""
    if src.language == "python":
        return _python_scopes(src)
    out: List[_Scope] = []
    stack: List[_Scope] = []
    boundary = 0
    code = src.code
    for m in re.finditer(r"[{};]", code):
        ch = m.group(0)
        if ch == "{":
            header = code[boundary:m.start()]
            name, test = None, bool(re.search(r"#\[cfg\(test\)\]", header))
            found = list(_CONTAINER.finditer(header))
            if found and not re.search(r"\bcompanion\s+object\s*$", header):
                last = found[-1]
                name = (last.group(1) or last.group(2) or "").split(".")[-1] or None
            stack.append(_Scope(m.start(), len(code), name, test))
        elif ch == "}" and stack:
            scope = stack.pop()
            scope.end = m.end()
            if scope.name or scope.test:
                out.append(scope)
        boundary = m.end()
    out.extend(s for s in stack if s.name or s.test)
    return sorted(out, key=lambda s: (s.start, -s.end))


def _python_scopes(src: _Source) -> List[_Scope]:
    out = []
    for m in _PY_CLASS.finditer(src.code):
        indent = len(m.group(1).expandtabs())
        body = src.code.find("\n", m.end()) + 1 or len(src.code)
        end = len(src.code)
        for line in re.finditer(r"(?m)^([ \t]*)\S", src.code[body:]):
            if len(line.group(1).expandtabs()) <= indent:
                end = body + line.start()
                break
        out.append(_Scope(m.start(), end, m.group(2)))
    return out


def _module_name(path: str, src: _Source) -> Optional[str]:
    """How other files name this file's top level: a Rust module, a Go package, a Python module."""
    if src.language == "go":
        m = re.search(r"(?m)^package\s+(\w+)", src.code)
        return m.group(1) if m else None
    stem = posixpath.splitext(posixpath.basename(path))[0]
    if src.language == "rust":
        if stem in ("lib", "main"):
            return None
        return posixpath.basename(posixpath.dirname(path)) or None if stem == "mod" else stem
    if src.language == "python":
        return posixpath.basename(posixpath.dirname(path)) or None if stem == "__init__" else stem
    return None


class ConstantTable:
    """String constants by the names code uses for them, per language family: `tag::REMOTE`, `Tag.remote`,
    `Keys.TYPE`; bare names in their own file (only where the declaration's container encloses the use) and, for
    CONSTANT_CASE names, project-wide. A name with two values is ambiguous and resolves to nothing."""

    def __init__(self) -> None:
        self.qualified: Dict[Tuple[str, str], Set[str]] = {}
        self.bare: Dict[Tuple[str, str], Set[str]] = {}
        self.local: Dict[str, Dict[str, List[Tuple[str, int, int]]]] = {}  # path -> name -> (value, scope span)
        self.names: Set[str] = set()  # every declared name: most chains in a body name none of them

    def add(self, src: _Source, functions: List[Tuple[int, int]], scopes: List[_Scope]) -> None:
        family, module = family_of(src.language), _module_name(src.path, src)
        for name, offset, value in _declarations(src):
            line = src.line_of(offset)
            if any(a <= line <= b for a, b in functions):
                continue  # a local: its literal is in the function's own body already
            around = [s for s in scopes if s.start <= offset < s.end and s.name]
            chain = [s.name for s in around]
            inner = around[-1] if around else None
            self.names.add(name)
            self.local.setdefault(src.path, {}).setdefault(name, []).append(
                (value, inner.start if inner else 0, inner.end if inner else 1 << 62))
            self.bare.setdefault((family, name), set()).add(value)
            names = ([module] if module else []) + chain
            for i in range(len(names)):
                self.qualified.setdefault((family, ".".join(names[i:] + [name])), set()).add(value)

    def resolve(self, path: str, family: str, chain: List[str], offset: int = -1) -> Optional[str]:
        if not any(part in self.names for part in chain):
            return None
        for i in range(len(chain)):
            for j in range(min(len(chain), i + 3), i + 1, -1):
                values = self.qualified.get((family, ".".join(chain[i:j])))
                if values:
                    return next(iter(values)) if len(values) == 1 else None
        head = chain[0]
        here = {v for v, a, b in self.local.get(path, {}).get(head, []) if offset < 0 or a <= offset < b}
        values = here or (self.bare.get((family, head)) if _CONSTANT_NAME.match(head) else None)
        return next(iter(values)) if values and len(values) == 1 else None


def _depths(code: str, positions: List[int]) -> List[int]:
    """Bracket depth at each (sorted) position."""
    out, depth, k = [], 0, 0
    marks = [(m.start(), 1 if m.group(0) in "([{" else -1) for m in re.finditer(r"[()\[\]{}]", code)]
    for pos in positions:
        while k < len(marks) and marks[k][0] < pos:
            depth += marks[k][1]
            k += 1
        out.append(depth)
    return out


def _declarations(src: _Source) -> Iterable[Tuple[str, int, str]]:
    """(name, offset, value) of every `NAME = "literal"` the language treats as a constant."""
    code = src.code

    def value_at(offset: int) -> Optional[str]:
        hit = src.strings.get(offset)
        if hit is None:
            return None
        rest = code[hit[0]:hit[0] + 40].lstrip(" \t")
        return hit[1] if (not rest or rest[0] in ";,\n)}" or rest.startswith("//")) and KEYLIKE.match(hit[1]) else None

    if src.language == "python":
        found = list(_PY_DECL.finditer(code))
        depth = _depths(code, [m.start(2) for m in found])
        for m, d in zip(found, depth):
            value = value_at(m.end())
            if value is not None and d == 0:  # inside a bracket it is a keyword argument, not a constant
                yield m.group(2), m.start(2), value
        return
    for m in _DECL.finditer(code):
        value = value_at(m.end())
        if value is not None:
            yield m.group(1) or m.group(2), m.start(), value
    if src.language == "go":
        for block in _GO_BLOCK.finditer(code):
            end = code.find(")", block.end())
            for m in _GO_ITEM.finditer(code, block.end(), end if end > 0 else len(code)):
                value = value_at(m.end())
                if value is not None:
                    yield m.group(1), m.start(1), value


