@dataclass
class FunctionVocabulary:
    node_id: str
    language: str
    path: str
    line_start: int
    line_end: int
    name: str
    keys: Dict[str, int]  # literal -> first line it appears on (directly or through a constant)
    roles: Dict[str, str] = field(default_factory=dict)  # literal -> "w", "r" or "wr" where the code says


def vocabularies(actual: ActualMap, root: Path, stats: Optional[Dict[str, Any]] = None) -> List[FunctionVocabulary]:
    """Key-like literals of every function outside tests, generated and vendored code, constants resolved."""
    return _collect(actual, Path(root), stats)[0]


def _collect(actual: ActualMap, root: Path, stats: Optional[Dict[str, Any]] = None
             ) -> Tuple[List[FunctionVocabulary], Dict[str, _Source]]:
    vendored = vendored_rules(lambda rel: _read(root, rel))
    by_file: Dict[str, List[ActualNode]] = {}
    files: Set[str] = set()
    skipped = {"test": set(), "vendored": set(), "generated": set()}
    for n in actual.nodes:
        if n.location is None or n.external:
            continue
        path = n.location.path
        if not language_of(path):
            continue
        if VENDORED_PATH.search(path) or vendored(path):
            skipped["vendored"].add(path)
            continue
        files.add(path)
        if n.kind in ("function", "method"):
            by_file.setdefault(path, []).append(n)
    sources: Dict[str, _Source] = {}
    scopes: Dict[str, List[_Scope]] = {}
    table = ConstantTable()
    for path in sorted(files):
        if is_test_path(path):
            skipped["test"].add(path)
            continue
        text = _read(root, path)
        if text is None:
            skipped["generated"].add(path)
            continue
        src = sources[path] = _Source(path, text, language_of(path))
        scopes[path] = _scopes(src)
        ranges = [(n.location.line_start, n.location.line_end) for n in by_file.get(path, [])]
        table.add(src, ranges, scopes[path])
    out: List[FunctionVocabulary] = []
    too_small = 0
    for path in sorted(by_file):
        src = sources.get(path)
        if src is None:
            continue
        family = family_of(src.language)
        test_spans = [(s.start, s.end) for s in scopes[path] if s.test]
        for n in sorted(by_file[path], key=lambda n: (n.location.line_start, n.id)):
            start, end = src.offset_of(n.location.line_start), src.offset_of(n.location.line_end + 1)
            if n.location.line_end >= len(src.line_starts):
                end = len(src.code)
            if any(a <= start < b for a, b in test_spans) or n.name in TEST_MACROS or \
                    _has_test_attribute(src, n.location.line_start):
                continue
            keys: Dict[str, int] = {}
            roles: Dict[str, str] = {}

            def note(value: str, a: int, b: int) -> None:
                role = _role(src.code, a, b)
                if role and role not in roles.get(value, ""):
                    roles[value] = "".join(sorted(roles.get(value, "") + role))

            for offset, value in src.strings_between(start, end):
                if KEYLIKE.match(value) and len(value) >= 2:
                    keys.setdefault(value, src.line_of(offset))
                    note(value, offset, src.strings[offset][0])
            for m in _CHAIN.finditer(src.code, start, end):
                chain = _SPLIT_CHAIN.split(m.group(0))
                value = table.resolve(path, family, chain, m.start())
                if value is not None and len(value) >= 2:
                    line = src.line_of(m.start())
                    if keys.get(value, line + 1) > line:
                        keys[value] = line
                    note(value, m.start(), m.end())
            if len(keys) >= MIN_NAMED_VOCABULARY:
                out.append(FunctionVocabulary(n.id, src.language, path, n.location.line_start, n.location.line_end,
                                              n.name, keys, roles))
            elif keys:
                too_small += 1
    if stats is not None:
        stats.update({k: len(v) for k, v in skipped.items()})
        stats["functions"] = len(out)
        stats["too_small"] = too_small
        stats["languages"] = sorted({v.language for v in out})
    return out, sources


def _has_test_attribute(src: _Source, line: int) -> bool:
    above = src.code[src.offset_of(max(1, line - 3)):src.offset_of(line + 1)]
    return bool(TEST_ATTRIBUTE.search(above))


# ====================================================================== pairing and grouping


def normalized_name(name: str) -> str:
    """parse_stream, parseStream and ParseStream are one name."""
    return re.sub(r"[^a-z0-9]", "", name.split(".")[-1].lower())


def _weights(vocabs: List[FunctionVocabulary]) -> Dict[str, float]:
    df: Dict[str, int] = {}
    for v in vocabs:
        for key in v.keys:
            df[key] = df.get(key, 0) + 1
    total = len(vocabs) + 1
    return {key: math.log(total / count) + 0.1 for key, count in df.items()}


def pair_score(a: FunctionVocabulary, b: FunctionVocabulary, idf: Dict[str, float]) -> Tuple[float, int]:
    """(literal overlap, shared keys): the rare keys both use, against the smaller copy and against both (a copy may
    be split into helpers in one language), plus a small bonus for the same name. Not capped: two perfect overlaps
    are told apart by the name; callers cap it for display."""
    shared = set(a.keys) & set(b.keys)
    if not shared:
        return 0.0, 0
    ws = sum(idf[k] for k in shared)
    wa, wb = sum(idf[k] for k in a.keys), sum(idf[k] for k in b.keys)
    score = 0.5 * ws / min(wa, wb) + 0.5 * 2 * ws / (wa + wb)
    if normalized_name(a.name) == normalized_name(b.name):
        score += NAME_BONUS
    return round(score, 4), len(shared)


def side_of(v: FunctionVocabulary, keys: Iterable[str]) -> str:
    """'w' when the function mostly writes these keys, 'r' when it mostly reads them, '' when it is not clear."""
    keys = list(keys)
    w = sum(1 for k in keys if v.roles.get(k) == "w")
    r = sum(1 for k in keys if v.roles.get(k) == "r")
    if w >= 2 * r and 3 * w >= len(keys) and w:
        return "w"
    if r >= 2 * w and 3 * r >= len(keys) and r:
        return "r"
    return ""


def two_ends(a: FunctionVocabulary, b: FunctionVocabulary) -> bool:
    """One writes the shared keys and the other reads them: a producer and its consumer, not two copies."""
    shared = set(a.keys) & set(b.keys)
    return {side_of(a, shared), side_of(b, shared)} == {"w", "r"}


def _small_ok(a: FunctionVocabulary, b: FunctionVocabulary) -> bool:
    """A vocabulary under MIN_VOCABULARY pairs only by name, and only when all its keys are in the other's."""
    small, big = (a, b) if len(a.keys) <= len(b.keys) else (b, a)
    if len(small.keys) >= MIN_VOCABULARY:
        return True
    return normalized_name(a.name) == normalized_name(b.name) and set(small.keys) <= set(big.keys)


def find_pairs(vocabs: List[FunctionVocabulary], min_score: float = DEFAULT_MIN_SCORE,
               linked: Optional[Callable[[str, str], bool]] = None
               ) -> Tuple[List[Tuple[float, str, str]], Dict[Tuple[str, str], float], Dict[str, float]]:
    """Mutual-best pairs of different languages: (overlap, id, id), every scored candidate, and the weights.

    `linked(a, b)` drops two functions one of which calls the other (the Java side of a JNI call and the Rust
    function behind it exchange the same keys by design: they are two ends of one link, not two copies). Ties are
    broken by more shared keys, then by the library function over an example, test or fixture, then by id."""
    idf = _weights(vocabs)
    by_id = {v.node_id: v for v in vocabs}
    index: Dict[str, List[str]] = {}
    for v in vocabs:
        for key in v.keys:
            index.setdefault(key, []).append(v.node_id)
    candidates: Set[Tuple[str, str]] = set()
    for key in sorted(index):
        ids = index[key]
        if len(ids) > MAX_DF:
            continue
        for i, a in enumerate(ids):
            for b in ids[i + 1:]:
                if by_id[a].language != by_id[b].language:
                    candidates.add((a, b) if a < b else (b, a))
    scores: Dict[Tuple[str, str], float] = {}
    best: Dict[Tuple[str, str], Tuple[tuple, str]] = {}  # (node, other language) -> (rank, other)
    for a, b in sorted(candidates):
        score, shared = pair_score(by_id[a], by_id[b], idf)
        small = min(len(by_id[a].keys), len(by_id[b].keys)) < MIN_VOCABULARY
        if shared < (MIN_NAMED_VOCABULARY if small else MIN_SHARED) or score < min_score or \
                not _small_ok(by_id[a], by_id[b]) or (linked is not None and linked(a, b)):
            continue
        scores[(a, b)] = score
        for x, y in ((a, b), (b, a)):
            slot = (x, by_id[y].language)
            rank = (score, shared, not is_side_path(by_id[y].path))
            held = best.get(slot)
            if held is None or rank > held[0] or (rank == held[0] and y < held[1]):
                best[slot] = (rank, y)
    pairs = [(s, a, b) for (a, b), s in scores.items()
             if best[(a, by_id[b].language)][1] == b and best[(b, by_id[a].language)][1] == a]
    return sorted(pairs, key=lambda p: (-p[0], p[1], p[2])), scores, idf


def group_pairs(vocabs: List[FunctionVocabulary], pairs: List[Tuple[float, str, str]],
                scores: Dict[Tuple[str, str], float],
                linked: Optional[Callable[[str, str], bool]] = None) -> List[Dict[str, Any]]:
    """Mutual-best pairs joined, best first, while no language gets two copies (a big function that does the work
    of several small ones elsewhere must not glue their groups together) and no member of one side calls a member
    of the other (a helper of a copy is part of that copy); then a function whose best partner is in a group joins
    it when its language is there already (a second copy in one language, listed separately) and it does not call
    or get called by its language's copy: under the same name as its partner or as that copy when the pair is strong
    or its keys are mostly the partner's, under another name only when the pair is strong and its vocabulary is not
    small (a store's load and save share one enum's strings with a builder, and are not copies of it)."""
    by_id = {v.node_id: v for v in vocabs}
    parent: Dict[str, str] = {}

    def find(x: str) -> str:
        while parent.setdefault(x, x) != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x

    def any_link(xs: Iterable[str], ys: Iterable[str]) -> bool:
        return linked is not None and any(linked(x, y) for x in xs for y in ys)

    langs: Dict[str, Set[str]] = {}
    members: Dict[str, List[str]] = {}
    kept: List[Tuple[float, str, str]] = []
    for s, a, b in pairs:
        ra, rb = find(a), find(b)
        la, lb = langs.setdefault(ra, {by_id[a].language}), langs.setdefault(rb, {by_id[b].language})
        ma, mb = members.setdefault(ra, [a]), members.setdefault(rb, [b])
        if ra == rb or la & lb or any_link(ma, mb):
            continue
        root, other = min(ra, rb), max(ra, rb)
        parent[other] = root
        langs[root] = la | lb
        members[root] = sorted(set(ma) | set(mb))
        kept.append((s, a, b))
    groups: Dict[str, Dict[str, Any]] = {}
    for s, a, b in kept:
        g = groups.setdefault(find(a), {"core": set(), "extra": set(), "scores": []})
        g["core"].update((a, b))
        g["scores"].append(min(s, 1.0))
    core_of = {m: r for r, g in groups.items() for m in g["core"]}
    best_partner: Dict[str, Tuple[float, str]] = {}
    for (a, b), s in sorted(scores.items()):
        for x, y in ((a, b), (b, a)):
            if x not in core_of and y in core_of and (s, y) > best_partner.get(x, (0.0, "")):
                best_partner[x] = (s, y)
    for x, (s, y) in sorted(best_partner.items()):
        g = groups[core_of[y]]
        same = [m for m in g["core"] if by_id[m].language == by_id[x].language]
        if not same or any_link([x], same):
            continue
        coverage = len(set(by_id[x].keys) & set(by_id[y].keys)) / max(1, len(by_id[x].keys))
        named = normalized_name(by_id[x].name) in {normalized_name(by_id[m].name) for m in same + [y]}
        if (named and (s >= HIGH_SCORE or coverage >= EXTRA_COVERAGE)) or \
                (s >= HIGH_SCORE and len(by_id[x].keys) >= SMALL_VOCABULARY):
            g["extra"].add(x)
    out = []
    for g in groups.values():
        out.append({"core": sorted(g["core"]), "extra": sorted(g["extra"]),
                    "members": sorted(g["core"]) + sorted(g["extra"]),
                    "score": round(sum(g["scores"]) / len(g["scores"]), 3)})
    return out


# ====================================================================== who reaches a copy


_FFI_VIAS = {"ffi", "jni", "uniffi", "frb"}


def reach_index(actual: ActualMap) -> Dict[str, List[Tuple[str, Optional[str]]]]:
    """callee -> [(caller, bridge via or None)] over resolved calls and links between languages."""
    callers: Dict[str, List[Tuple[str, Optional[str]]]] = {}
    for e in actual.edges:
        if e.kind != "calls" or e.from_id == e.to_id:
            continue
        if e.bridge:
            if not e.bridge.get("missing"):
                callers.setdefault(e.to_id, []).append((e.from_id, str(e.bridge.get("via") or "")))
        elif e.confidence == "resolved":
            callers.setdefault(e.to_id, []).append((e.from_id, None))
    return callers


NO_CALLERS = "no proven callers in the map"


def reach_of(node_id: str, callers: Dict[str, List[Tuple[str, Optional[str]]]], paths: Dict[str, str]) -> str:
    """How the program gets to a copy, from the map's proven calls: through another language, from app code,
    only from examples and tests, or by no call the map proves (a call inside a macro is not one)."""
    seen, todo, vias, roots = {node_id}, [node_id], set(), []
    while todo and len(seen) < MAX_REACH_NODES:
        x = todo.pop()
        mine = callers.get(x, [])
        if not mine and x != node_id:
            roots.append(x)
        for caller, via in mine:
            if via and not is_side_path(paths.get(caller, "")):
                vias.add(via)
            if caller not in seen:
                seen.add(caller)
                todo.append(caller)
    if vias:
        if vias & _FFI_VIAS:
            return "reached from FFI/JNI"
        from pmap.langs.bridges import VIA_NAMES

        return "reached from " + ", ".join(sorted(VIA_NAMES.get(v, v) for v in vias))
    if not roots:
        roots = [n for n in seen if n != node_id]  # a cycle with no outside caller
    if any(not is_side_path(paths.get(r, "")) for r in roots):
        return "reached from app code"
    if roots:
        return "examples/tests only"
    return NO_CALLERS


def _called_by_name(v: FunctionVocabulary, src: Optional[_Source]) -> str:
    """A call of the function by its name elsewhere in its own file, which the map did not resolve (a macro body)."""
    if src is None:
        return ""
    short = v.name.split(".")[-1]
    lo, hi = src.offset_of(v.line_start), src.offset_of(v.line_end + 1)
    for m in re.finditer(r"(?<![\w.$])" + re.escape(short) + r"\s*\(", src.code):
        if not lo <= m.start() < hi:
            return f"; called by name at {v.path}:{src.line_of(m.start())} (a call the map did not resolve)"
    return ""


# ====================================================================== the whole search


def linker(actual: ActualMap, hops: int = 4) -> Callable[[str, str], bool]:
    """Whether one function reaches the other within a few proven calls or links between languages, or both
    handle one channel (each platform's handler of a Flutter channel: gaps cover what one of them lacks)."""
    calls: Dict[str, Set[str]] = {}
    handlers: Dict[str, Set[str]] = {}  # node -> channels it handles
    for e in actual.edges:
        if e.kind == "calls" and (e.confidence == "resolved" or (e.bridge and not e.bridge.get("missing"))):
            calls.setdefault(e.from_id, set()).add(e.to_id)
        if e.bridge and e.bridge.get("via") in ("channel", "event-channel", "message-channel"):
            for target in [e.to_id] + list(e.candidates or []):
                handlers.setdefault(target, set()).add(str(e.bridge.get("name")))

    def reaches(a: str, b: str) -> bool:
        frontier, seen = {a}, {a}
        for _ in range(hops):
            frontier = {y for x in frontier for y in calls.get(x, ())} - seen
            if b in frontier:
                return True
            seen |= frontier
        return False

    return lambda a, b: bool(handlers.get(a, set()) & handlers.get(b, set())) or reaches(a, b) or reaches(b, a)


def _bridged_from(actual: ActualMap, paths: Dict[str, str]) -> Dict[str, Set[str]]:
    """node -> files whose code reaches it through a channel, FFI or JNI link."""
    out: Dict[str, Set[str]] = {}
    for e in actual.edges:
        if e.kind == "calls" and e.bridge and not e.bridge.get("missing") and e.from_id in paths:
            out.setdefault(e.to_id, set()).add(paths[e.from_id])
    return out


def find_twins(actual: ActualMap, root: Path, min_score: float = DEFAULT_MIN_SCORE,
               stats: Optional[Dict[str, Any]] = None) -> List[TwinGroup]:
    """Candidate groups, copies first, then the two ends of one format; `stats` (when given) gets what was read."""
    root = Path(root)
    vocabs, sources = _collect(actual, root, stats)
    link = linker(actual)
    pairs, scores, idf = find_pairs(vocabs, min_score, link)
    by_id = {v.node_id: v for v in vocabs}
    callers = reach_index(actual)
    paths = {n.id: n.location.path for n in actual.nodes if n.location is not None}
    bridged = _bridged_from(actual, paths)

    def ends(a: str, b: str) -> bool:
        return two_ends(by_id[a], by_id[b]) or by_id[b].path in bridged.get(a, ()) or \
            by_id[a].path in bridged.get(b, ())

    copies = [p for p in pairs if not ends(p[1], p[2])]
    copy_scores = {k: s for k, s in scores.items() if not ends(*k)}
    copy_groups = group_pairs(vocabs, copies, copy_scores, link)
    taken = {m for g in copy_groups for m in g["members"]}  # one function, one group: a copy first
    format_pairs = [p for p in pairs if ends(p[1], p[2]) and p[1] not in taken and p[2] not in taken]
    out = []
    for kind, group_list in (("copies", copy_groups), ("ends", group_pairs(vocabs, format_pairs, {}, link))):
        for g in group_list:
            out.append(_twin_group(g, kind, by_id, idf, callers, paths, sources))
    if stats is not None:
        stats["unread"] = _unread_files(root)
    return sorted(out, key=lambda g: (g.kind != "copies", -g.score, g.title, g.id))


def _twin_group(g: Dict[str, Any], kind: str, by_id: Dict[str, FunctionVocabulary], idf: Dict[str, float],
                callers: Dict[str, List[Tuple[str, Optional[str]]]], paths: Dict[str, str],
                sources: Dict[str, _Source]) -> TwinGroup:
    members = [by_id[m] for m in g["members"]]
    langs_of: Dict[str, Set[str]] = {}
    for v in members:
        for key in v.keys:
            langs_of.setdefault(key, set()).add(v.language)
    shared = {k for k, ls in langs_of.items() if len(ls) > 1}
    extra = set(g["extra"])
    links: List[List[Any]] = []
    best: Dict[str, Tuple[float, int, str, bool]] = {}
    for i, a in enumerate(members):
        for b in members[i + 1:]:
            if a.language == b.language:
                continue
            s, n = pair_score(a, b, idf)
            links.append([a.node_id, b.node_id, round(min(s, 1.0), 3), n])
            same = normalized_name(a.name) == normalized_name(b.name)
            for x, y in ((a, b), (b, a)):
                if (s, n) > best.get(x.node_id, (-1.0, 0, "", False))[:2]:
                    best[x.node_id] = (s, n, y.name, same)
    twin_members = []
    for v in members:
        reach = reach_of(v.node_id, callers, paths)
        if reach == NO_CALLERS:
            reach += _called_by_name(v, sources.get(v.path))
        s, n, partner, same = best.get(v.node_id, (0.0, 0, "", False))
        twin_members.append(TwinMember(v.node_id, v.language, v.path, v.line_start, v.line_end, v.name, len(v.keys),
                                       len(shared & set(v.keys)), reach, v.node_id in extra, round(min(s, 1.0), 3),
                                       partner, n, same))
    twin_members.sort(key=lambda m: (m.same_language, m.language, m.path, m.line_start, m.node_id))
    ranked = sorted(shared, key=lambda k: (-len(langs_of[k]), -idf[k], k))
    names: List[str] = []
    for m in twin_members:
        if m.name not in names and not m.same_language:
            names.append(m.name)
    digest = hashlib.sha1("\n".join(sorted(g["core"])).encode("utf-8")).hexdigest()[:10]
    return TwinGroup(f"twin:{digest}", " / ".join(names[:3]) + (" / ..." if len(names) > 3 else ""),
                     g["score"], twin_members, ranked[:MAX_EVIDENCE], kind, max(0, len(ranked) - MAX_EVIDENCE),
                     sorted(links))


def _unread_files(root: Path) -> Dict[str, int]:
    """Source files of languages the map does not read, by extension."""
    from pmap.langs import SKIP_DIRS

    out: Dict[str, int] = {}
    for _dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [d for d in dirnames if d not in SKIP_DIRS and not d.startswith(".")]
        for name in filenames:
            ext = posixpath.splitext(name)[1]
            if ext in UNREAD_EXTS and not name.startswith("._"):
                out[ext] = out.get(ext, 0) + 1
    return dict(sorted(out.items()))


