def _lang_name(language: str) -> str:
    from pmap.langs.bridges import LANGUAGE_NAMES

    return LANGUAGE_NAMES.get(language, language)


def _not_mapped(languages: Optional[Dict[str, dict]]) -> List[str]:
    return sorted(_lang_name(k) for k, v in (languages or {}).items() if v.get("files") and not v.get("mapped"))


def format_twins(groups: List[TwinGroup], markdown: bool = False, languages: Optional[Dict[str, dict]] = None,
                 stats: Optional[Dict[str, Any]] = None) -> str:
    """The groups as text; `languages` (the map's) and `stats` (find_twins') add what was not searched."""
    head = "## " if markdown else ""
    item = "- " if markdown else "  "
    lines: List[str] = []
    missing = _not_mapped(languages)
    if missing:
        lines.append(f"Not searched: {', '.join(missing)} {'is' if len(missing) == 1 else 'are'} not mapped "
                     "(`pmap langs install`); copies in them cannot be found.")
    copies = [g for g in groups if g.kind == "copies"]
    ends = [g for g in groups if g.kind != "copies"]
    if not groups:
        mapped = [k for k, v in (languages or {}).items() if v.get("files") and v.get("mapped")]
        if languages is not None and len(mapped) < 2:
            lines.append("No candidates searched for: fewer than two languages are mapped.")
        else:
            lines.append("No candidate groups: no function shares enough rare string literals with a function in "
                         "another language (static).")
    if copies:
        lines.append(f"{head}{len(copies)} candidate group{'s' if len(copies) != 1 else ''}: functions in different "
                     "languages that use the same rare string literals. Each may be a hand-written copy, the other "
                     "end of one format, or unrelated (static, not proof; `--exec` compares outputs)")
        for g in copies:
            lines.extend(_format_group(g, markdown, item))
    if ends:
        lines.append("")
        lines.append(f"{head}{len(ends)} pair{'s' if len(ends) != 1 else ''} that look like two ends of one format: "
                     "one side writes these keys and the other reads them (producer and consumer, not copies)")
        for g in ends:
            lines.extend(_format_group(g, markdown, item))
    if stats:
        lines.append("")
        lines.append(_footer(stats))
    return "\n".join(lines) + "\n"


def _format_group(g: TwinGroup, markdown: bool, item: str) -> List[str]:
    out = ["", f"{'### ' if markdown else ''}{g.title}  (literal overlap {g.score:.2f}, {g.id})"]
    for m in g.members:
        tag = "same language, " if m.same_language else ""
        where = f"{m.path}:{m.line_start}"
        pair = (f"overlap {m.score:.2f} with {m.partner}: {m.pair_shared} of {m.vocabulary_size} literals, "
                f"same name: {'yes' if m.same_name else 'no'}" if m.partner else "")
        small = ", small vocabulary" if m.vocabulary_size < SMALL_VOCABULARY else ""
        out.append(f"{item}{'`' + where + '`' if markdown else where}  {m.name}  ({_lang_name(m.language)}, {tag}"
                   f"{m.reach}; {pair}{small}; shares {m.shared_count} of {m.vocabulary_size} with the group)")
    if g.evidence:
        shown = ", ".join(f'"{k}"' for k in g.evidence)
        out.append(f"{item}shared literals: {shown}" + (f" (+{g.more_evidence} more)" if g.more_evidence else ""))
    return out


def _footer(stats: Dict[str, Any]) -> str:
    langs = ", ".join(_lang_name(x) for x in stats.get("languages", []))
    parts = [f"read {stats.get('functions', 0)} functions with {MIN_NAMED_VOCABULARY} or more literals"
             + (f" in {langs}" if langs else "")]
    skipped = [f"{stats[k]} {k} file{'s' if stats[k] != 1 else ''}" for k in ("test", "generated", "vendored")
               if stats.get(k)]
    if skipped:
        parts.append("skipped " + ", ".join(skipped))
    unread = stats.get("unread") or {}
    if unread:
        parts.append("not read: " + ", ".join(f"{n} {ext} file{'s' if n != 1 else ''} (no {UNREAD_EXTS[ext]} reader)"
                                              for ext, n in unread.items()))
    parts.append(f"functions with fewer than {MIN_VOCABULARY} literals pair only with a function of the same name "
                 f"({stats.get('too_small', 0)} with 1-2 literals cannot pair)")
    return "; ".join(parts)


def twins_for_hints(groups: List[TwinGroup], min_score: float = HIGH_SCORE) -> Dict[str, Any]:
    """The compact form the note after an edit reads from the cache: node id -> the copies in other languages
    whose own pair with it scores `min_score` or more, each with the literals that pair shares. Two ends of one
    format are left out (a change to a writer does not ask for the same change in its reader), and so are pairs of
    different names over a small vocabulary (a UI label and a decoder that share one enum's strings)."""
    out: Dict[str, Any] = {}
    for g in groups:
        if g.kind != "copies":
            continue
        by_id = {m.node_id: m for m in g.members}
        pair = {}
        for a, b, s, n in g.links:
            pair[(a, b)] = pair[(b, a)] = (float(s), int(n))
        for m in g.members:
            others = []
            for o in g.members:
                s, n = pair.get((m.node_id, o.node_id), (0.0, 0))
                weak = normalized_name(m.name) != normalized_name(o.name) and \
                    min(m.vocabulary_size, o.vocabulary_size) < SMALL_VOCABULARY
                if o.language != m.language and s >= min_score and not weak:
                    others.append([o.path, o.line_start, o.name, o.language, n, s])
            if others:
                others.sort(key=lambda x: (-x[5], x[0], x[1]))
                out[m.node_id] = {"group": g.id, "size": by_id[m.node_id].vocabulary_size, "others": others}
    return out

